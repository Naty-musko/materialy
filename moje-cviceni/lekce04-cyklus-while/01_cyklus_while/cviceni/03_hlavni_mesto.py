# Cvičení 3 – Cyklus while
# Doplň kód pod zadání a soubor spusť (Run).

# Ptej se uživatele "Jaké je hlavní město Česka? " tak dlouho,
#    dokud nenapíše "Praha". Pak vypiš "Správně!".
hledej = input("Jaké je hlavní město Česka? ")
while hledej != "Praha":
    hledej = input("Jaké je hlavní město Česka? ")
print("Správně!")   


